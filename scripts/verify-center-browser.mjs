await p.click('button[aria-label="关闭 Tab"] >> nth=1');
await p.waitForFunction(()=>document.querySelectorAll('.tab').length===1);
const saved=await p.evaluate(()=>window.__test.notes.a.title==='未保存草稿');
if(!saved)throw new Error('Retry failed to persist draft');
await p.waitForSelector('input[aria-label="便签标题"]');
const active=await p.evaluate(()=>document.querySelector('input[aria-label="便签标题"]').value);
if(active!=='中心验收')throw new Error('Closing active tab failed to select remaining tab');
console.log('PASS: center create/edit, trash/undo, task removal/editor undo, reminder UI, failed-save protection and retry');
