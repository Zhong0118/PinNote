const p=task.page('p1');
const fs=await import('node:fs/promises');
const root='/Users/zhongxu/Desktop/0-Inbox/PinNote';
const fixture=await fs.readFile(`${root}/tests/browser-fixture.txt`,'utf8');
await p.goto('http://127.0.0.1:1420/center');
await p.evaluate(fixture);
await p.waitForSelector('button[aria-label="新建便签"]');
await p.click('button[aria-label="新建便签"]');
await p.waitForSelector('.milkdown .editor');
await p.fill('input[aria-label="便签标题"]','中心验收');
await p.waitForFunction(()=>Object.values(window.__test.notes).some(n=>n.title==='中心验收'));
await p.click('button[aria-label="更多操作"]');
await p.click('text="移到回收站"');
await p.waitForSelector('text="已在回收站"');
await p.click('text="撤销移除"');
await p.waitForSelector('.milkdown .editor');
await p.click('button.note-row >> nth=1');
await p.waitForSelector('li[data-checked="true"]');
await p.click('button[aria-label="更多操作"]');
await p.click('text="移除已完成项（可撤销）"');
await p.waitForFunction(()=>!document.querySelector('li[data-checked="true"]'));
await p.focus('.milkdown .editor');
await p.keyboard.press('Meta+z');
await p.waitForSelector('li[data-checked="true"]');
await p.click('button[aria-label="更多操作"]');
await p.click('text="设置提醒"');
await p.click('text="30 分钟后"');
